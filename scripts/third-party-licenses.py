"""Regenerates THIRD-PARTY-LICENSES.md from Cargo (run: `just licenses`).

Lists the crates built for the app and the sign-in helper on Linux, marks
the ones used only while building (build scripts, code generators), and
prints the license identifiers of the crates that end up in the programs,
for the PKGBUILD's license array. Standard library only.
"""

import collections
import json
import re
import subprocess
import sys
from datetime import date

TARGET = "x86_64-unknown-linux-gnu"
OWN = {"cosmic-ext-deskfeed", "cosmic-ext-deskfeed-signin", "cosmic-ext-deskfeed-lines"}

# Git crates without a license field, checked against the license file in
# their source repository (2026-10-17).
FROM_LICENSE_FILE = {
    "apply": "Unlicense",
    "cosmic-config": "MPL-2.0",
    "cosmic-config-derive": "MPL-2.0",
    "cosmic-settings-daemon": "MPL-2.0",
    "cosmic-theme": "MPL-2.0",
    "libcosmic": "MPL-2.0",
    "dnd": "MIT",
    "mime": "MIT",
    "iced_accessibility": "MIT",
}

SYSTEM = """## System software (not part of this repository)

| Software | License | How it is used |
|---|---|---|
| FreeRDP (`sdl-freerdp3`) | Apache-2.0 | Separate program, started by the app |
| WebKitGTK 6 | LGPL-2.1-or-later (parts BSD) | Dynamically linked by the sign-in helper only |
| GTK 4 | LGPL-2.1-or-later | Dynamically linked by the sign-in helper only |
| A Secret Service (oo7, GNOME Keyring, …) | Varies | Separate program, used over D-Bus |
"""


def crates(edges: str) -> set[str]:
    out = subprocess.run(
        ["cargo", "tree", "--workspace", "--locked", "-e", edges, "--prefix", "none",
         "--format", "{p}", "--target", TARGET],
        check=True, capture_output=True, text=True,
    ).stdout
    found = set()
    for line in out.splitlines():
        line = re.sub(r" \(.*$", "", line).strip()
        if line:
            found.add(line)
    return found


def main() -> None:
    shipped = crates("normal")
    all_built = crates("normal,build")
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        check=True, capture_output=True, text=True,
    ).stdout)
    rows = []
    for p in meta["packages"]:
        key = f"{p['name']} v{p['version']}"
        if key not in all_built or p["name"] in OWN:
            continue
        lic = p.get("license")
        note = ""
        if not lic:
            lic = FROM_LICENSE_FILE.get(p["name"])
            if lic is None:
                sys.exit(f"no license known for {key}: add it to FROM_LICENSE_FILE")
            note = " ¹"
        rows.append((p["name"], p["version"], lic + note, key not in shipped,
                     p.get("repository") or ""))
    rows.sort()

    in_programs = [r for r in rows if not r[3]]
    summary = collections.Counter(r[2].replace(" ¹", "") for r in in_programs)
    lines = [
        "# Third-party software", "",
        "Deskfeed is MIT-licensed ([LICENSE](./LICENSE)). This file lists the software it is "
        "built with or runs with, and their licenses. Generated by "
        "`scripts/third-party-licenses.py` (`just licenses`); don't edit by hand.", "",
        SYSTEM,
        f"## Rust crates ({len(rows)})", "",
        f"From `Cargo.lock`, for Linux, generated {date.today().isoformat()}. "
        f"{len(in_programs)} are compiled into `cosmic-ext-deskfeed` or "
        "`cosmic-ext-deskfeed-signin`; the ones marked **build only** run while building "
        "(build scripts, the desktop-entry generator) and are not part of the programs. "
        "License expressions are as each crate declares them; where one says *OR*, "
        "either license may be chosen.", "",
        "Compiled into the programs: "
        + ", ".join(f"{k}: {v}" for k, v in summary.most_common()), "",
        "¹ No license field in the crate's metadata; taken from the license file in its "
        "source repository. libcosmic and its COSMIC crates are MPL-2.0 (file-level "
        "copyleft: it applies to changes to those files, not to this app's own code).", "",
        "| Crate | Version | License | Build only | Source |", "|---|---|---|---|---|",
    ]
    for name, version, lic, build_only, repo in rows:
        lines.append(f"| {name} | {version} | {lic} | {'yes' if build_only else ''} | {repo} |")
    with open("THIRD-PARTY-LICENSES.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    ids = collections.Counter()
    for r in in_programs:
        for tok in re.split(r"\s+OR\s+|\s+AND\s+|/|[()]", r[2].replace(" ¹", "")):
            tok = re.sub(r"\s+WITH\s+.*", "", tok).strip()
            if tok:
                ids[tok] += 1
    print(f"{len(rows)} crates, {len(in_programs)} in the programs.")
    print("License identifiers in the programs:", " ".join(sorted(ids)))


if __name__ == "__main__":
    main()
